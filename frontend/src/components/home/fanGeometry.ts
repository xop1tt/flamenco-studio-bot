// Геометрия векторного веера (StageArt.FanArt) — отдельный модуль без JSX,
// чтобы клиентская хореография (choreography.ts) могла считать масштаб
// веера, не затягивая в клиентский бандл саму SVG-разметку.
//
// Система координат viewBox: шарнир веера — (0, 0), лист раскрыт вверх.

/** Внешний радиус листа, единицы viewBox. */
export const FAN_R = 1000;
/** Внутренний радиус листа: ниже него — только пластины с просветами. */
export const FAN_RI = 380;
/** Половина угла раскрытия, градусы от вертикали. */
export const FAN_HALF = 80;
/** Число складок (пар граней) между пластинами. */
export const FAN_PLEATS = 18;

export const FAN_BOX = { x: -1030, y: -1040, w: 2060, h: 1110 } as const;

/** Внешний радиус листа в долях ширины элемента — для пересчёта px ↔ scale. */
export const FAN_RADIUS_RATIO = FAN_R / FAN_BOX.w;
/** Внутренний радиус в долях внешнего — зона пластин, которую нельзя
 * выводить на экран, когда веер должен закрыть его целиком. */
export const FAN_INNER_RATIO = FAN_RI / FAN_R;
